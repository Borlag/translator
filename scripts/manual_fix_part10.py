CAPTION_SHEET_RE = re.compile(r"^Ремонт Корпус стойки рисунок 601\s*-\s*Лист\s*(\d+)$")
CAPTION_BUSH_RE = re.compile(r"^Ремонт Корпус стойки - Втулка рисунок 602$")


def normalize_ws(text: str) -> str:
    return re.sub(r"\s+", " ", text.replace("\xa0", " ")).strip()


def set_node_text(node: etree._Element, value: str) -> None:
    node.text = value
    if value[:1].isspace() or value[-1:].isspace():
        node.set(XML_SPACE, "preserve")
    elif XML_SPACE in node.attrib:
        del node.attrib[XML_SPACE]


def text_nodes(container: etree._Element) -> list[etree._Element]:
    return container.xpath(".//w:t | .//a:t", namespaces=NS)


def paragraph_text(paragraph: etree._Element) -> str:
    return "".join(node.text or "" for node in text_nodes(paragraph))


def set_paragraph_text(paragraph: etree._Element, value: str) -> None:
    nodes = text_nodes(paragraph)
    if not nodes:
        return
    set_node_text(nodes[0], value)
    for node in nodes[1:]:
        set_node_text(node, "")


def maybe_replace_text(current: str) -> str | None:
    normalized = normalize_ws(current)
    if not normalized:
        return None

    updated = normalized
    if updated in EXACT_REPLACEMENTS:
        updated = EXACT_REPLACEMENTS[updated]

    match = CAPTION_SHEET_RE.match(updated)
    if match:
        updated = f"Ремонт корпуса стойки, рисунок 601, лист {match.group(1)}"
    elif CAPTION_BUSH_RE.match(updated):
        updated = "Ремонт корпуса стойки - втулка, рисунок 602"

    if updated != normalized:
        return updated
    return None


def patch_xml_bytes(data: bytes, stats: Counter[str], part_name: str) -> bytes:
    root = etree.fromstring(data)
    part_changes = 0

    for paragraph in root.xpath(".//w:p", namespaces=NS):
        current = paragraph_text(paragraph)
        replacement = maybe_replace_text(current)
        if replacement is None:
            continue
        set_paragraph_text(paragraph, replacement)
        part_changes += 1

        if "ПРЕДОСТЕРЕЖЕНИЕ." in replacement:
            stats["caution_fixed"] += 1
        elif "Спецификация материала" in replacement or "σв =" in replacement or "Loctite марки 601" in replacement:
            stats["table_terms_fixed"] += 1
        else:
            stats["body_or_figure_fixed"] += 1

    if part_changes:
        stats["paragraphs_changed"] += part_changes
        stats[f"part::{part_name}"] += part_changes

    return etree.tostring(root, encoding="UTF-8", xml_declaration=True, standalone="yes")


def patch_docx(docx_path: Path) -> Counter[str]:
    stats: Counter[str] = Counter()

    with tempfile.TemporaryDirectory() as tmpdir:
        temp_path = Path(tmpdir) / docx_path.name

        with zipfile.ZipFile(docx_path, "r") as src, zipfile.ZipFile(temp_path, "w") as dst:
            for item in src.infolist():
                data = src.read(item.filename)
                is_target = item.filename == "word/document.xml"

                if is_target:
                    data = patch_xml_bytes(data, stats, item.filename)

                dst.writestr(item, data)

        temp_path.replace(docx_path)

    return stats


def main() -> int:
    parser = argparse.ArgumentParser(description="Apply GPT review fixes to part10_ru.docx in place.")
    parser.add_argument("--docx", required=True, help="DOCX file to patch")
    parser.add_argument("--report", required=True, help="Path to JSON report")
    args = parser.parse_args()

    docx_path = Path(args.docx).resolve()
    report_path = Path(args.report).resolve()
    report_path.parent.mkdir(parents=True, exist_ok=True)

    stats = patch_docx(docx_path)
    payload = {
        "docx": str(docx_path),
        "stats": dict(stats),
    }
    report_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

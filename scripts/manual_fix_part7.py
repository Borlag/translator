def _patch_document_xml(docx_path: Path) -> int:
    changed_files = 0
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp_path = Path(tmpdir) / "patched.docx"
        with ZipFile(docx_path, "r") as zin, ZipFile(tmp_path, "w", compression=ZIP_DEFLATED) as zout:
            for info in zin.infolist():
                data = zin.read(info.filename)
                if info.filename == "word/document.xml":
                    text = data.decode("utf-8")
                    updated = text
                    for source, target in XML_REPLACEMENTS.items():
                        updated = updated.replace(source, target)
                    updated = updated.replace(">to<", ">-<")
                    updated = re.sub(r"(?<=\d)\s+to\s+(?=\d)", "-", updated, flags=re.IGNORECASE)
                    updated = re.sub(r"(?<=\d)\s+and\s+(?=\d)", ", ", updated, flags=re.IGNORECASE)
                    if updated != text:
                        data = updated.encode("utf-8")
                        changed_files += 1
                zout.writestr(info, data)
        tmp_path.replace(docx_path)
    return changed_files


def apply_fixes(docx_path: Path) -> dict[str, object]:
    doc = Document(str(docx_path))
    paragraph_updates = 0
    table_updates = 0

    for idx, text in PARAGRAPH_FIXES.items():
        _set_paragraph_text_minimal(doc.paragraphs[idx], text)
        paragraph_updates += 1

    for (table_idx, row_idx, cell_idx), text in TABLE_FIXES.items():
        cell = doc.tables[table_idx].rows[row_idx].cells[cell_idx]
        _set_cell_text_minimal(cell, text)
        table_updates += 1

    doc.save(str(docx_path))
    table_font_floor_runs = int(enforce_table_readability(docx_path))
    document_xml_patch_files = _patch_document_xml(docx_path)
    return {
        "docx": str(docx_path),
        "paragraph_updates": paragraph_updates,
        "table_updates": table_updates,
        "table_font_floor_runs": table_font_floor_runs,
        "document_xml_patch_files": document_xml_patch_files,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Apply manual Russian fixes for part7 CMM translation.")
    parser.add_argument("--docx", required=True, help="Translated DOCX to patch in place")
    parser.add_argument("--report", required=True, help="Path to the JSON patch report")
    args = parser.parse_args()

    docx_path = Path(args.docx).resolve()
    report_path = Path(args.report).resolve()
    report_path.parent.mkdir(parents=True, exist_ok=True)

    payload = apply_fixes(docx_path)
    report_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(payload, ensure_ascii=False, indent=2))
    return 0



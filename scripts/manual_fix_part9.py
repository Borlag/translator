def normalize_ws(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def set_node_text(node: etree._Element, value: str) -> None:
    node.text = value
    if value[:1].isspace() or value[-1:].isspace():
        node.set(XML_SPACE, "preserve")
    elif XML_SPACE in node.attrib:
        del node.attrib[XML_SPACE]


def text_nodes_in_txbx(txbx: etree._Element) -> list[etree._Element]:
    return txbx.xpath(".//w:t", namespaces=NS)


def textbox_text(txbx: etree._Element) -> str:
    return normalize_ws("".join(node.text or "" for node in text_nodes_in_txbx(txbx)))


